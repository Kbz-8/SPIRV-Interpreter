#define CHECK_RESULT(expr) do { \
	SpvResult check_result = (expr); \
	if (check_result != SPV_RESULT_SUCCESS) \
	{ \
		fprintf(stderr, "%s failed with %d\n", #expr, check_result); \
		return -1; \
	} \
} while (0)

